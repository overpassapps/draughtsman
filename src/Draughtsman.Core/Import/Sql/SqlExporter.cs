using System.Text;
using Draughtsman.Core.Enums;
using Draughtsman.Core.Models;
using Draughtsman.Core.Schemas;

namespace Draughtsman.Core.Import.Sql;

/// <summary>The DDL for a diagram's entities, and what could not be carried into it.</summary>
/// <param name="Sql">The script; every warning is also in it as a leading <c>--</c> comment.</param>
/// <param name="Warnings">Nodes and relationships that were skipped or completed, and why.</param>
public sealed record SqlExportResult(string Sql, IReadOnlyList<string> Warnings);

/// <summary>
/// Writes an entity diagram as <c>CREATE TABLE</c> DDL: each entity node becomes a table (its label is the name, its
/// <c>props.columns</c> the columns, <c>PK</c> rows the primary key, <c>not null</c> the nullability), and each
/// <c>association</c> edge between two entities becomes a foreign key on the many end that names the edge's label columns
/// and references the other table's primary key. The mirror of <see cref="SqlImporter"/>: an import, export and import
/// gives the same tables, columns, keys and relationships. Foreign keys are added after every table exists
/// (<c>ALTER TABLE ... ADD CONSTRAINT</c>), except in SQLite, which cannot add a constraint later and so has them inline.
/// </summary>
public static class SqlExporter
{
    public static SqlExportResult Export(Document document, SqlDialect dialect = SqlDialect.TSql)
    {
        if (dialect == SqlDialect.Auto)
        {
            dialect = SqlDialect.TSql;
        }

        var warnings = new List<string>();
        OrderedDictionary<string, Table> tables = ReadTables(document, dialect, warnings);
        List<Relationship> relationships = PlanRelationships(document, tables, warnings);

        var script = new StringBuilder();
        script.Append("-- ").Append(document.Title.ReplaceLineEndings(" ")).Append(": generated by Draughtsman (").Append(DialectLabel(dialect)).AppendLine(")");
        foreach (string warning in warnings)
        {
            script.Append("-- warning: ").AppendLine(warning.ReplaceLineEndings(" "));
        }

        foreach (Table table in tables.Values)
        {
            script.AppendLine();
            WriteTable(script, table, relationships.Where(r => r.Child == table).ToList(), dialect);
        }

        if (dialect != SqlDialect.Sqlite)
        {
            foreach (Relationship relationship in relationships)
            {
                script.AppendLine();
                script.Append("alter table ").Append(QualifiedName(relationship.Child, dialect)).Append(" add ").Append(ForeignKey(relationship, dialect)).AppendLine();
                script.AppendLine(Terminator(dialect));
            }
        }

        // StringBuilder.AppendLine writes the platform's newline; a generated .sql file is the same bytes on every host, so it is always "\n".
        return new SqlExportResult(script.ToString().ReplaceLineEndings("\n"), warnings);
    }

    #region Reading the diagram

    private sealed class Table(Node node, string schema, string name)
    {
        public Node Node { get; } = node;

        public string Schema { get; } = schema;

        public string Name { get; } = name;

        public List<Column> Columns { get; } = [];

        public List<string> PrimaryKey { get; } = [];

        public List<IReadOnlyList<string>> Uniques { get; } = [];

        public Column? Find(string name)
        {
            return Columns.FirstOrDefault(c => string.Equals(c.Name, name, StringComparison.OrdinalIgnoreCase));
        }
    }

    private sealed class Column(string name, string type, bool notNull, bool foreignKey)
    {
        public string Name { get; } = name;

        public string Type { get; } = type;

        public bool NotNull { get; set; } = notNull;

        public bool ForeignKey { get; } = foreignKey;
    }

    private sealed record Relationship(string Name, Table Child, Table Parent, IReadOnlyList<string> ChildColumns, IReadOnlyList<string> ParentColumns);

    private static OrderedDictionary<string, Table> ReadTables(Document document, SqlDialect dialect, List<string> warnings)
    {
        var tables = new OrderedDictionary<string, Table>(StringComparer.Ordinal);
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (Node node in document.Nodes)
        {
            if (!IsEntity(node))
            {
                warnings.Add($"Node '{node.Label}' ({node.Id}) is not an entity, so it has no table.");
                continue;
            }

            (string schema, string name) = SplitName(node);
            if (!names.Add($"{schema}.{name}"))
            {
                warnings.Add($"Two entities are both called '{name}'; '{node.Id}' was skipped.");
                continue;
            }

            var table = new Table(node, schema, name);
            foreach (string line in ErShapeLibrary.ColumnLines(node.Props))
            {
                ErColumn parsed = ErShapeLibrary.ParseColumn(line);
                if (parsed.Name.Length == 0 || table.Find(parsed.Name) is not null)
                {
                    continue;
                }

                bool primary = parsed.Keys.Contains("PK");
                table.Columns.Add(new Column(parsed.Name, SqlTypeMapper.Map(parsed.Type, dialect), primary || parsed.Nullable == ErNullability.NotNull, parsed.Keys.Contains("FK")));
                if (primary)
                {
                    table.PrimaryKey.Add(parsed.Name);
                }
            }

            if (table.Columns.Count == 0)
            {
                warnings.Add($"Entity '{name}' has no columns, so it has no table.");
                continue;
            }

            tables[node.Id] = table;
        }

        return tables;
    }

    private static bool IsEntity(Node node)
    {
        return ErShapeLibrary.IsErShape(node.Shape) || node.Kind is "entity" or "weak-entity";
    }

    /// <summary>A label is the table name, optionally schema-qualified (<c>journey.Orders</c>); a name with no letters falls back to the node id.</summary>
    private static (string Schema, string Name) SplitName(Node node)
    {
        string label = string.Join(' ', node.Label.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
        int dot = label.LastIndexOf('.');
        if (dot > 0 && dot < label.Length - 1)
        {
            return (label[..dot], label[(dot + 1)..]);
        }

        return (string.Empty, label.Length > 0 ? label : node.Id);
    }

    #endregion

    #region Relationships

    private static List<Relationship> PlanRelationships(Document document, OrderedDictionary<string, Table> tables, List<string> warnings)
    {
        var relationships = new List<Relationship>();
        var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var claimed = new HashSet<(Table, string)>();

        foreach (Edge edge in document.Edges)
        {
            if (!tables.TryGetValue(edge.From.Node, out Table? from) || !tables.TryGetValue(edge.To.Node, out Table? to))
            {
                if (document.Nodes.Any(n => n.Id == edge.From.Node && IsEntity(n)) && document.Nodes.Any(n => n.Id == edge.To.Node && IsEntity(n)))
                {
                    warnings.Add($"Relationship '{edge.Id}' joins an entity that has no table, so it was skipped.");
                }

                continue;
            }

            // The importer draws a relationship the database does not enforce as a dashed edge labelled "column (no FK)"; it documents the schema, so writing it as a constraint would enforce what the source chose not to.
            if (edge.Label?.TrimEnd().EndsWith(SqlImporter.NoForeignKeyMarker, StringComparison.OrdinalIgnoreCase) == true)
            {
                continue;
            }

            if (edge.Kind != "association")
            {
                warnings.Add($"Edge '{edge.Id}' is a '{edge.Kind}' edge, not an association, so it is not a relationship.");
                continue;
            }

            bool startMany = IsMany(edge.Style?.ArrowStart);
            bool endMany = IsMany(edge.Style?.ArrowEnd);
            if (startMany && endMany)
            {
                warnings.Add($"Relationship '{edge.Id}' between '{from.Name}' and '{to.Name}' is many-to-many, which needs a table of its own; draw that table and two one-to-many relationships.");
                continue;
            }

            // The crow's foot marks the referencing (child) table. With none, the edge runs from child to parent, the way the importer draws it.
            (Table child, Table parent, ArrowHead? childEnd, ArrowHead? parentEnd) = endMany && !startMany
                ? (to, from, edge.Style?.ArrowEnd, edge.Style?.ArrowStart)
                : (from, to, edge.Style?.ArrowStart, edge.Style?.ArrowEnd);

            if (parent.PrimaryKey.Count == 0)
            {
                warnings.Add($"Relationship '{edge.Id}' references '{parent.Name}', which has no primary key (mark a column PK), so it was skipped.");
                continue;
            }

            List<string>? childColumns = ChildColumns(edge, child, parent, claimed);
            if (childColumns is null)
            {
                bool optional = parentEnd is ArrowHead.ZeroOrOne or ArrowHead.ZeroOrMany;
                childColumns = AddForeignKeyColumns(child, parent, optional, warnings, edge);
            }
            else if (childColumns.Count != parent.PrimaryKey.Count)
            {
                warnings.Add($"Relationship '{edge.Id}' names {childColumns.Count} column(s) on '{child.Name}' but '{parent.Name}' has a {parent.PrimaryKey.Count}-column primary key, so it was skipped.");
                continue;
            }

            foreach (string column in childColumns)
            {
                claimed.Add((child, column.ToLowerInvariant()));
            }

            bool oneToOne = childEnd is ArrowHead.One or ArrowHead.ZeroOrOne or ArrowHead.OneAndOnlyOne;
            if (oneToOne && !SamePrimaryKey(child, childColumns))
            {
                child.Uniques.Add(childColumns);
            }

            relationships.Add(new Relationship(UniqueName($"FK_{Sanitise(child.Name)}_{Sanitise(parent.Name)}", used), child, parent, childColumns, parent.PrimaryKey.ToList()));
        }

        return relationships;
    }

    private static bool IsMany(ArrowHead? head)
    {
        return head is ArrowHead.Many or ArrowHead.ZeroOrMany or ArrowHead.OneOrMany;
    }

    /// <summary>
    /// The child columns a relationship joins on: those the edge's label names, else the child's key columns no other
    /// relationship has taken. Null when neither says, and the relationship then gets columns of its own.
    /// </summary>
    private static List<string>? ChildColumns(Edge edge, Table child, Table parent, HashSet<(Table, string)> claimed)
    {
        if (!string.IsNullOrWhiteSpace(edge.Label))
        {
            List<string> named = edge.Label.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries)
                .Select(n => child.Find(n)?.Name ?? string.Empty)
                .ToList();
            if (named.Count > 0 && named.All(n => n.Length > 0))
            {
                return named;
            }
        }

        List<string> free = child.Columns.Where(c => c.ForeignKey && !claimed.Contains((child, c.Name.ToLowerInvariant()))).Select(c => c.Name).ToList();
        return free.Count == parent.PrimaryKey.Count ? free : null;
    }

    /// <summary>A relationship drawn without saying which columns carry it gets one column per parent key column, named for the parent.</summary>
    private static List<string> AddForeignKeyColumns(Table child, Table parent, bool optional, List<string> warnings, Edge edge)
    {
        var added = new List<string>();
        foreach (string key in parent.PrimaryKey)
        {
            Column source = parent.Find(key)!;
            string name = $"{parent.Name}_{key}";
            for (int suffix = 2; child.Find(name) is not null; suffix++)
            {
                name = $"{parent.Name}_{key}_{suffix}";
            }

            child.Columns.Add(new Column(name, source.Type, !optional, true));
            added.Add(name);
        }

        warnings.Add($"Relationship '{edge.Id}' did not say which columns of '{child.Name}' it joins on, so {string.Join(", ", added)} {(added.Count == 1 ? "was" : "were")} added; name the columns in the edge label to choose them.");
        return added;
    }

    private static bool SamePrimaryKey(Table table, IReadOnlyList<string> columns)
    {
        return columns.Count == table.PrimaryKey.Count && columns.All(c => table.PrimaryKey.Contains(c, StringComparer.OrdinalIgnoreCase));
    }

    private static string UniqueName(string candidate, HashSet<string> used)
    {
        string name = candidate;
        for (int suffix = 2; !used.Add(name); suffix++)
        {
            name = $"{candidate}_{suffix}";
        }

        return name;
    }

    private static string Sanitise(string name)
    {
        return new string(name.Select(c => char.IsAsciiLetterOrDigit(c) ? c : '_').ToArray());
    }

    #endregion

    #region Writing SQL

    private static void WriteTable(StringBuilder script, Table table, List<Relationship> inlineKeys, SqlDialect dialect)
    {
        var items = new List<string>();
        foreach (Column column in table.Columns)
        {
            bool notNull = column.NotNull || table.PrimaryKey.Contains(column.Name, StringComparer.OrdinalIgnoreCase);
            string nullability = notNull ? " not null" : dialect == SqlDialect.TSql ? " null" : string.Empty;
            string type = column.Type.Length > 0 ? " " + column.Type : string.Empty;
            items.Add($"{Quote(column.Name, dialect)}{type}{nullability}");
        }

        if (table.PrimaryKey.Count > 0)
        {
            string name = dialect is SqlDialect.TSql or SqlDialect.Postgres ? $"constraint {Quote("PK_" + Sanitise(table.Name), dialect)} " : string.Empty;
            items.Add($"{name}primary key ({ColumnList(table.PrimaryKey, dialect)})");
        }

        int unique = 0;
        foreach (IReadOnlyList<string> columns in table.Uniques)
        {
            unique++;
            string name = $"UQ_{Sanitise(table.Name)}_{string.Join('_', columns.Select(Sanitise))}";
            items.Add($"constraint {Quote(name.Length > 0 ? name : $"UQ_{unique}", dialect)} unique ({ColumnList(columns, dialect)})");
        }

        if (dialect == SqlDialect.Sqlite)
        {
            items.AddRange(inlineKeys.Select(key => ForeignKey(key, dialect)));
        }

        script.Append("create table ").AppendLine(QualifiedName(table, dialect));
        script.AppendLine("(");
        script.AppendLine(string.Join(",\n", items.Select(item => "    " + item)));
        script.AppendLine(")");
        script.AppendLine(Terminator(dialect));
    }

    private static string ForeignKey(Relationship key, SqlDialect dialect)
    {
        return $"constraint {Quote(key.Name, dialect)} foreign key ({ColumnList(key.ChildColumns, dialect)}) references {QualifiedName(key.Parent, dialect)} ({ColumnList(key.ParentColumns, dialect)})";
    }

    private static string ColumnList(IEnumerable<string> columns, SqlDialect dialect)
    {
        return string.Join(", ", columns.Select(c => Quote(c, dialect)));
    }

    /// <summary>T-SQL and PostgreSQL keep the schema; MySQL and SQLite have no schema within a database, so it is folded into the table name.</summary>
    private static string QualifiedName(Table table, SqlDialect dialect)
    {
        switch (dialect)
        {
            case SqlDialect.TSql:
                return $"{Quote(table.Schema.Length > 0 ? table.Schema : "dbo", dialect)}.{Quote(table.Name, dialect)}";
            case SqlDialect.Postgres:
                return table.Schema.Length > 0 ? $"{Quote(table.Schema, dialect)}.{Quote(table.Name, dialect)}" : Quote(table.Name, dialect);
            default:
                return Quote(table.Schema.Length > 0 ? $"{table.Schema}_{table.Name}" : table.Name, dialect);
        }
    }

    private static string Quote(string identifier, SqlDialect dialect)
    {
        return dialect switch
        {
            SqlDialect.TSql => $"[{identifier.Replace("]", "]]", StringComparison.Ordinal)}]",
            SqlDialect.MySql => $"`{identifier.Replace("`", "``", StringComparison.Ordinal)}`",
            _ => $"\"{identifier.Replace("\"", "\"\"", StringComparison.Ordinal)}\"",
        };
    }

    private static string Terminator(SqlDialect dialect)
    {
        return dialect == SqlDialect.TSql ? "go" : ";";
    }

    private static string DialectLabel(SqlDialect dialect)
    {
        return dialect switch
        {
            SqlDialect.TSql => "T-SQL",
            SqlDialect.Postgres => "PostgreSQL",
            SqlDialect.MySql => "MySQL",
            _ => "SQLite",
        };
    }

    #endregion
}
